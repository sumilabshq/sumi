import fs from "node:fs";
import path from "node:path";
import { CliRefusal } from "./cli-output.js";
import { CONTRACT_ENTRY, contractTextOf } from "./module-contract.js";
import { JOINED_ENTRY, joinedTextOf } from "./module-joined.js";
import { packageKindOf } from "@widgetarium/eslint-plugin/domain-file";
import type { DeclaredModule } from "@widgetarium/eslint-plugin/module-declared";

const GENERATED_ENTRY = "generated/index.ts";
const ROOT_ENTRY = "index.ts";
const GENERATED_FOLDER = "generated/";
const RE_EXPORT = /^\s*export\s+(\*|\{[^}]*\}|type\s+\{[^}]*\})\s+from\s/m;
const GATEWAYS_ENTRY = "generated/gateways.ts";
export const GENERATED_HEADER =
	"// @generated by widgetarium generate. Do not edit: every change here is overwritten on the next run.\n";

const FEATURES = "features";
const SCHEMAS = "shared/schema";
const GATEWAYS = "gateways";
const GATEWAY_FILE = /^gateways\/[^/]+\/(([^/]+)\/\2|[^/]+)\.gateway\.ts$/;
const CONTRACT_FILE = "contract.ts";
const SCHEMA_FILE = /\.schema\.ts$/;
const UI_ENTRY = "shared/ui/index.ts";
const LIB_ENTRY = "shared/lib/index.ts";
const MODULE_FILE = "module.ts";
const SCRIPT = /\.ts$/;
const RE_EXPORT_GENERATED = "the generator wrote a re-export into {file}; generated/ holds only generated code";
const UNREAD_MODULE =
	"{file} exports no const built by serverModule(...), clientModule(...) or module(...) the generator can read; it reads module.ts, never runs it";

export interface GeneratedFile {
	readonly entry: string;
	readonly text: string;
}

export interface GeneratedPackage {
	readonly files: readonly GeneratedFile[];
	readonly strays: readonly string[];
}

export function generatedPackageOf(folder: string, shownAs: string): GeneratedPackage {
	const kind = packageKindOf(folder);

	if (kind === null) {
		throw new CliRefusal(UNREAD_MODULE.replace("{file}", `${shownAs}/${MODULE_FILE}`));
	}

	if (kind.kind === "client-package") {
		return onlyGeneratedCodeIn(folder, clientFilesOf(folder));
	}

	if (kind.module.runs === "anywhere") {
		return onlyGeneratedCodeIn(folder, requestsModuleFilesOf(folder, kind.module));
	}

	return {
		files: [...handledModuleFilesOf(folder, kind.module), ...gatewaysFilesOf(folder)],
		strays: [],
	};
}

function onlyGeneratedCodeIn(folder: string, files: readonly GeneratedFile[]): GeneratedPackage {
	refuseGeneratedReExports(files);
	return { files, strays: strayEntriesOf(folder, files) };
}

function refuseGeneratedReExports(files: readonly GeneratedFile[]): void {
	const reExporting = files.find(({ entry, text }) => entry.startsWith(GENERATED_FOLDER) && RE_EXPORT.test(text));

	if (reExporting !== undefined) {
		throw new Error(RE_EXPORT_GENERATED.replace("{file}", reExporting.entry));
	}
}

function strayEntriesOf(folder: string, files: readonly GeneratedFile[]): string[] {
	const written = new Set(files.map(({ entry }) => entry));
	return filesUnder(folder, GENERATED_FOLDER).filter((entry) => !written.has(entry));
}

function handledModuleFilesOf(folder: string, declared: DeclaredModule): GeneratedFile[] {
	const features = filesUnder(folder, FEATURES);
	return [
		{ entry: GENERATED_ENTRY, text: GENERATED_HEADER + entryTextOf(folder, declared, features) },
		{ entry: JOINED_ENTRY, text: GENERATED_HEADER + joinedTextOf(folder, declared, features) },
	];
}

function gatewaysFilesOf(folder: string): GeneratedFile[] {
	const gateways = filesUnder(folder, GATEWAYS).filter((relative) => GATEWAY_FILE.test(relative));
	return gateways.length === 0
		? []
		: [{ entry: GATEWAYS_ENTRY, text: GENERATED_HEADER + gateways.map(reExportOf).join("") }];
}

function clientFilesOf(folder: string): GeneratedFile[] {
	const entries = [UI_ENTRY, LIB_ENTRY].filter((relative) => fs.existsSync(path.join(folder, relative)));
	return [{ entry: ROOT_ENTRY, text: GENERATED_HEADER + entries.map(rootReExportOf).join("") }];
}

function requestsModuleFilesOf(folder: string, declared: DeclaredModule): GeneratedFile[] {
	return [
		{ entry: CONTRACT_ENTRY, text: GENERATED_HEADER + contractTextOf(folder, declared.name) },
		{ entry: ROOT_ENTRY, text: GENERATED_HEADER + rootReExportOf(CONTRACT_ENTRY) },
	];
}

function entryTextOf(folder: string, declared: DeclaredModule, features: readonly string[]): string {
	const contracts = features.filter((relative) => path.basename(relative) === CONTRACT_FILE);
	const schemas = filesUnder(folder, SCHEMAS).filter((relative) => SCHEMA_FILE.test(relative));
	const ui = declared.runs === "client" && fs.existsSync(path.join(folder, UI_ENTRY)) ? [UI_ENTRY] : [];
	return [...contracts, ...schemas, ...ui].map(reExportOf).join("");
}

function filesUnder(folder: string, inside: string): string[] {
	const root = path.join(folder, inside);
	if (!fs.existsSync(root)) return [];
	return fs
		.readdirSync(root, { recursive: true, withFileTypes: true })
		.filter((entry) => entry.isFile())
		.map((entry) => path.relative(folder, path.join(entry.parentPath, entry.name)).split(path.sep).join("/"))
		.sort();
}

function rootReExportOf(relative: string): string {
	return `export * from "./${relative.replace(SCRIPT, ".js")}";\n`;
}

function reExportOf(relative: string): string {
	return `export * from "../${relative.replace(SCRIPT, ".js")}";\n`;
}
