import fs from "node:fs";
import path from "node:path";
import { CliRefusal } from "./cli-output.js";
import { z } from "zod";
import type { CallExpression } from "@babel/types";
import { CONTRACT_ENTRY, SERVER_CONTRACT_FILE, moduleContractsOf } from "./module-contract.js";
import type { HandledItem } from "./module-contract.js";
import { importsIn } from "./contract-imports.js";
import { MODULE_SPECIFIER } from "./contract-needs.js";
import { JOINED_ENTRY, joinedTextOf } from "./module-joined.js";
import { contractPackageFilesOf } from "./contract-package.js";
import { FRAMEWORK } from "./scaffold-names.js";
import { filesUnder } from "./template-files.js";
import { chainOf, exportedConstsOf } from "@widgetarium/eslint-plugin/babel-chain";
import { packageKindOf } from "@widgetarium/eslint-plugin/domain-file";
import { parsedSourceOf } from "@widgetarium/eslint-plugin/files";
import { fillTemplate } from "@widgetarium/eslint-plugin/fill-template";
import type { DeclaredModule } from "@widgetarium/eslint-plugin/module-declared";
import { jsonAt } from "@widgetarium/eslint-plugin/workspace";

export const COMMAND_ENTRY = "generated/command.ts";
export const HANDLED_ENTRY = "generated/handled.ts";

const GENERATED_ENTRY = "generated/index.ts";
const ROOT_ENTRY = "index.ts";
const ROOT_SERVER_ENTRY = "server.ts";
const GENERATED_FOLDER = "generated/";
const RE_EXPORT = /^\s*export\s+(\*|\{[^}]*\}|type\s+\{[^}]*\})\s+from\s/m;
const GATEWAYS_ENTRY = "generated/gateways.ts";
export const GENERATED_HEADER =
	"// @generated by widgetarium generate. Do not edit: every change here is overwritten on the next run.\n";

const FEATURES = "features/";
const SCHEMAS = "shared/schema/";
const GATEWAYS = "gateways/";
const GATEWAY_FILE = /^gateways\/[^/]+\/(([^/]+)\/\2|[^/]+)\.gateway\.ts$/;
const CONTRACT_FILE = "contract.ts";
const SCHEMA_FILE = /\.schema\.ts$/;
const UI_ENTRY = "shared/ui/index.ts";
const LIB_ENTRY = "shared/lib/index.ts";
const MODULE_FILE = "module.ts";
const SCRIPT = /\.ts$/;
const SERVER_EXPORT = "./server";
const PACKAGE_FILE = "package.json";
const RE_EXPORT_GENERATED = "the generator wrote a re-export into {file}; generated/ holds only generated code";
const NO_SERVER_EXPORT =
	'{package} lists server-only requests, and its package.json exports no "./server": add "./server" to its exports, or {package}/server never resolves';
const DANGLING_SERVER_EXPORT =
	'{package} exports "./server" in package.json, and its module lists nothing server-only: remove "./server" from its exports';
const HAND_WRITTEN_SERVER =
	"{package}: server.ts is not generated, and its module lists nothing server-only: remove server.ts, which re-exports nothing generate writes";
const UNREAD_MODULE =
	"{file} exports no const built by serverModule(...), clientModule(...) or module(...) the generator can read; it reads module.ts, never runs it";

export interface GeneratedFile {
	readonly entry: string;
	readonly text: string;
}

export interface GeneratedPackage {
	readonly files: readonly GeneratedFile[];
	readonly strays: readonly string[];
}

const NO_BUILDERS_IMPORT =
	'{package}: its requests take command and query from "#module", and its package.json "imports" names no "#module": add "#module" pointing at ./generated/command.ts';
const NOT_HANDLING =
	'{module}: module.ts must end with .handles(...handled), importing handled from "./generated/handled.js", and pass .handles() nothing else';
const HANDLES_METHOD = "handles";
const HANDLED_NAME = "handled";
const NO_EVENT = "never";
const HANDLED_SPECIFIER = "./generated/handled.js";
const SOURCE_SCRIPT = /\.tsx?$/;

const PackageManifestSchema = z.object({
	name: z.string(),
	exports: z.record(z.string(), z.unknown()).optional(),
	imports: z.record(z.string(), z.unknown()).optional(),
});

export function generatedPackageOf(folder: string, shownAs: string): GeneratedPackage {
	const kind = packageKindOf(folder);

	if (kind === null) {
		throw new CliRefusal(UNREAD_MODULE.replace("{file}", `${shownAs}/${MODULE_FILE}`));
	}

	if (kind.kind === "client-package") {
		return onlyGeneratedCodeIn(folder, clientFilesOf(folder));
	}

	if (kind.kind === "contract-package") {
		return onlyGeneratedCodeIn(folder, contractPackageFilesOf(folder, GENERATED_HEADER));
	}

	if (kind.module.runs === "anywhere") {
		return onlyGeneratedCodeIn(folder, requestsModuleFilesOf(folder, kind.module));
	}

	return {
		files: [...handledModuleFilesOf(folder, kind.module), ...gatewaysFilesOf(folder)],
		strays: [],
	};
}

function onlyGeneratedCodeIn(folder: string, files: readonly GeneratedFile[]): GeneratedPackage {
	refuseGeneratedReExports(files);
	return { files, strays: strayEntriesOf(folder, files) };
}

function refuseGeneratedReExports(files: readonly GeneratedFile[]): void {
	const reExporting = files.find(({ entry, text }) => entry.startsWith(GENERATED_FOLDER) && RE_EXPORT.test(text));

	if (reExporting !== undefined) {
		throw new Error(RE_EXPORT_GENERATED.replace("{file}", reExporting.entry));
	}
}

function strayEntriesOf(folder: string, files: readonly GeneratedFile[]): string[] {
	const written = new Set(files.map(({ entry }) => entry));
	const rootServer = isGeneratedFile(folder, ROOT_SERVER_ENTRY) ? [ROOT_SERVER_ENTRY] : [];
	return [...filesInside(folder, GENERATED_FOLDER), ...rootServer].filter((entry) => !written.has(entry));
}

function isGeneratedFile(folder: string, relative: string): boolean {
	const file = path.join(folder, relative);
	return fs.existsSync(file) && fs.readFileSync(file, "utf8").startsWith(GENERATED_HEADER);
}

function handledModuleFilesOf(folder: string, declared: DeclaredModule): GeneratedFile[] {
	const features = filesInside(folder, FEATURES);
	return [
		{ entry: GENERATED_ENTRY, text: GENERATED_HEADER + entryTextOf(folder, declared, features) },
		{ entry: JOINED_ENTRY, text: GENERATED_HEADER + joinedTextOf(folder, declared, features) },
	];
}

function gatewaysFilesOf(folder: string): GeneratedFile[] {
	const gateways = filesInside(folder, GATEWAYS).filter((relative) => GATEWAY_FILE.test(relative));
	return gateways.length === 0
		? []
		: [{ entry: GATEWAYS_ENTRY, text: GENERATED_HEADER + gateways.map(reExportOf).join("") }];
}

function clientFilesOf(folder: string): GeneratedFile[] {
	const entries = [UI_ENTRY, LIB_ENTRY].filter((relative) => fs.existsSync(path.join(folder, relative)));
	return [{ entry: ROOT_ENTRY, text: GENERATED_HEADER + entries.map(rootReExportOf).join("") }];
}

function requestsModuleFilesOf(folder: string, declared: DeclaredModule): GeneratedFile[] {
	const { contract, server, handledItems, ownedEvents } = moduleContractsOf(folder, declared.name);
	refuseServerEntryMismatch(folder, server !== null);
	refuseNotHandling(folder, declared.name);
	refuseNoBuildersImport(folder);
	const files = [
		{ entry: CONTRACT_ENTRY, text: GENERATED_HEADER + contract },
		{ entry: COMMAND_ENTRY, text: GENERATED_HEADER + commandTextOf(declared.name, ownedEvents) },
		{ entry: HANDLED_ENTRY, text: GENERATED_HEADER + handledTextOf(handledItems) },
		{ entry: ROOT_ENTRY, text: GENERATED_HEADER + rootReExportOf(CONTRACT_ENTRY) },
	];

	if (server === null) {
		return files;
	}

	return [
		...files,
		{ entry: SERVER_CONTRACT_FILE, text: GENERATED_HEADER + server },
		{ entry: ROOT_SERVER_ENTRY, text: GENERATED_HEADER + rootReExportOf(SERVER_CONTRACT_FILE) },
	];
}

function refuseServerEntryMismatch(folder: string, isServing: boolean): void {
	const manifest = PackageManifestSchema.parse(jsonAt(path.join(folder, PACKAGE_FILE)));
	const isExported = manifest.exports !== undefined && SERVER_EXPORT in manifest.exports;
	const said = { package: manifest.name };

	if (isServing && !isExported) {
		throw new CliRefusal(fillTemplate(NO_SERVER_EXPORT, said));
	}

	if (!isServing && isExported) {
		throw new CliRefusal(fillTemplate(DANGLING_SERVER_EXPORT, said));
	}

	if (
		!isServing &&
		fs.existsSync(path.join(folder, ROOT_SERVER_ENTRY)) &&
		!isGeneratedFile(folder, ROOT_SERVER_ENTRY)
	) {
		throw new CliRefusal(fillTemplate(HAND_WRITTEN_SERVER, said));
	}
}

function refuseNotHandling(folder: string, moduleName: string): void {
	const { body } = parsedSourceOf(path.join(folder, MODULE_FILE));
	const init = exportedConstsOf(body).find(({ name }) => name === moduleName)?.init;
	const handles = init === undefined ? undefined : chainOf(init).find(({ method }) => method === HANDLES_METHOD);
	const importsHandled = importsIn(body).some(
		({ local, specifier }) => local === HANDLED_NAME && specifier === HANDLED_SPECIFIER,
	);

	if (handles === undefined || !isHandledSpread(handles.call.arguments) || !importsHandled) {
		throw new CliRefusal(fillTemplate(NOT_HANDLING, { module: moduleName }));
	}
}

function isHandledSpread([spread, ...others]: CallExpression["arguments"]): boolean {
	return (
		others.length === 0 &&
		spread?.type === "SpreadElement" &&
		spread.argument.type === "Identifier" &&
		spread.argument.name === HANDLED_NAME
	);
}

function refuseNoBuildersImport(folder: string): void {
	const manifest = PackageManifestSchema.parse(jsonAt(path.join(folder, PACKAGE_FILE)));

	if (manifest.imports === undefined || !(MODULE_SPECIFIER in manifest.imports)) {
		throw new CliRefusal(fillTemplate(NO_BUILDERS_IMPORT, { package: manifest.name }));
	}
}

function commandTextOf(moduleName: string, ownedEvents: readonly HandledItem[]): string {
	const emitted = ownedEvents.length === 0 ? NO_EVENT : ownedEvents.map(({ name }) => `typeof ${name}`).sort().join(" | ");
	return [
		`import { buildersOf } from "${FRAMEWORK}";\n`,
		`import type { ${moduleName} } from "../module.js";\n`,
		...itemImportsOf(ownedEvents, "import type"),
		"\n",
		`export const { command, query, subscriber } = buildersOf<typeof ${moduleName}, ${emitted}>();\n`,
	].join("");
}

function handledTextOf(items: readonly HandledItem[]): string {
	const names = items.map(({ name }) => name).sort();
	const typeImport = `import type { ModuleItem } from "${FRAMEWORK}";\n`;
	const imports = itemImportsOf(items, "import").join("");
	return `${typeImport}${imports}\nexport const ${HANDLED_NAME}: readonly ModuleItem[] = [${names.join(", ")}];\n`;
}

function itemImportsOf(items: readonly HandledItem[], keyword: "import" | "import type"): string[] {
	const byFile = new Map<string, string[]>();

	for (const { name, file } of items) {
		byFile.set(file, [...(byFile.get(file) ?? []), name]);
	}

	return [...byFile]
		.sort(([first], [second]) => first.localeCompare(second))
		.map(
			([file, names]) =>
				`${keyword} { ${[...names].sort().join(", ")} } from "../${file.replace(SOURCE_SCRIPT, ".js")}";\n`,
		);
}

function entryTextOf(folder: string, declared: DeclaredModule, features: readonly string[]): string {
	const contracts = features.filter((relative) => path.basename(relative) === CONTRACT_FILE);
	const schemas = filesInside(folder, SCHEMAS).filter((relative) => SCHEMA_FILE.test(relative));
	const ui = declared.runs === "client" && fs.existsSync(path.join(folder, UI_ENTRY)) ? [UI_ENTRY] : [];
	return [...contracts, ...schemas, ...ui].map(reExportOf).join("");
}

function filesInside(folder: string, insideFolder: string): string[] {
	return filesUnder(folder, (relative) => relative.startsWith(insideFolder));
}

function rootReExportOf(relative: string): string {
	return `export * from "./${relative.replace(SCRIPT, ".js")}";\n`;
}

function reExportOf(relative: string): string {
	return `export * from "../${relative.replace(SCRIPT, ".js")}";\n`;
}
