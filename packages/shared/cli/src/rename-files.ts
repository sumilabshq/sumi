import fs from "node:fs";
import path from "node:path";
import { parseSync } from "@babel/core";
import type { types } from "@babel/core";
import { jsonAt, workspacePackagesIn } from "@widgetarium/eslint-plugin/workspace";
import { fillTemplate } from "@widgetarium/eslint-plugin/fill-template";
import { CliRefusal } from "./cli-output.js";

export interface ParsedScript {
	readonly file: string;
	readonly text: string;
	readonly ast: types.File;
}

export type Resolve = (from: string, specifier: string) => string | null;

type ParserPlugins = ("typescript" | "jsx")[];

const SKIPPED_FOLDERS: ReadonlySet<string> = new Set(["node_modules", "dist", "generated", "target", "dist-packages"]);
const UNSEARCHED_DOT_FOLDERS: ReadonlySet<string> = new Set([".claude", ".git"]);
const SCRIPT = /\.(ts|tsx|mts|cts|js|jsx|mjs|cjs)$/;
const DECLARATIONS = /\.d\.(ts|mts|cts)$/;
const TEXT_FILE = /\.(md|rs|json|css|html|yml|yaml)$/;
const SKIPPED_TEXT: ReadonlySet<string> = new Set(["package-lock.json"]);
const GENERATED_HEAD = "// @generated by ";
const RELATIVE_ENDINGS: readonly string[] = [
	"",
	".ts",
	".tsx",
	".mts",
	".js",
	".jsx",
	".mjs",
	"/index.ts",
	"/index.tsx",
	"/index.js",
];
const PARSER_PLUGINS: Readonly<Record<string, ParserPlugins>> = {
	".tsx": ["typescript", "jsx"],
	".ts": ["typescript"],
	".mts": ["typescript"],
	".cts": ["typescript"],
	".js": ["jsx"],
	".jsx": ["jsx"],
	".mjs": [],
	".cjs": [],
};
const PREFERRED_CONDITIONS: readonly string[] = ["source", "import", "default"];
const UNPARSED = "{file} cannot be parsed, so its uses cannot be renamed: {reason}";

export function scriptsUnder(root: string): string[] {
	return filesUnder(root, {
		isWanted: isScript,
		isEntered: (name) => !name.startsWith(".") && !SKIPPED_FOLDERS.has(name),
	});
}

export function mentionFilesUnder(root: string): string[] {
	return filesUnder(root, {
		isWanted: (file) => isText(file) || (isScript(file) && isInDotFolder(path.relative(root, file))),
		isEntered: (name) => !UNSEARCHED_DOT_FOLDERS.has(name) && !SKIPPED_FOLDERS.has(name),
	});
}

export function isHandWritten(text: string): boolean {
	return !text.startsWith(GENERATED_HEAD);
}

export function parsedScript(file: string, text: string): ParsedScript {
	try {
		const ast = parseSync(text, {
			filename: file,
			babelrc: false,
			configFile: false,
			sourceType: "unambiguous",
			parserOpts: { plugins: PARSER_PLUGINS[path.extname(file)] ?? [] },
		});

		if (ast === null) {
			throw new Error("no syntax tree");
		}

		return {
			file,
			text,
			ast,
		};
	} catch (failure) {
		const reason = failure instanceof Error ? failure.message : String(failure);
		throw new CliRefusal(fillTemplate(UNPARSED, { file, reason }));
	}
}

export function resolverIn(root: string): Resolve {
	const packages = workspacePackagesIn(root)
		.map(({ folder, name }) => ({ folder: path.join(root, folder), name }))
		.sort((one, other) => other.name.length - one.name.length);
	return (from, specifier) => {
		if (specifier.startsWith(".")) {
			return relativeFileOf(path.resolve(path.dirname(from), specifier));
		}

		const owner = packages.find(({ name }) => specifier === name || specifier.startsWith(`${name}/`));
		return owner === undefined ? null : exportedFileOf(owner.folder, `.${specifier.slice(owner.name.length)}`);
	};
}

function relativeFileOf(base: string): string | null {
	const stem = base.replace(/\.(js|mjs|jsx)$/, "");
	const candidates = [base, ...RELATIVE_ENDINGS.map((ending) => `${stem}${ending}`)];
	return candidates.find((candidate) => fs.existsSync(candidate) && fs.statSync(candidate).isFile()) ?? null;
}

function exportedFileOf(folder: string, subpath: string): string | null {
	const manifest = jsonAt(path.join(folder, "package.json"));
	const exportsField = typeof manifest === "object" && manifest !== null ? Reflect.get(manifest, "exports") : null;
	const entry = typeof exportsField === "object" && exportsField !== null ? Reflect.get(exportsField, subpath) : null;
	const target = targetOf(entry);
	return target === null ? null : relativeFileOf(path.join(folder, target));
}

function targetOf(entry: unknown): string | null {
	if (typeof entry === "string") {
		return entry;
	}

	if (typeof entry !== "object" || entry === null) {
		return null;
	}

	const values = [...PREFERRED_CONDITIONS.map((condition) => Reflect.get(entry, condition)), ...Object.values(entry)];

	for (const value of values) {
		const target = targetOf(value);

		if (target !== null) {
			return target;
		}
	}

	return null;
}

interface FileWalk {
	readonly isWanted: (file: string) => boolean;
	readonly isEntered: (folderName: string) => boolean;
}

function filesUnder(folder: string, walk: FileWalk): string[] {
	return fs.readdirSync(folder, { withFileTypes: true }).flatMap((entry) => {
		const full = path.join(folder, entry.name);

		if (entry.isDirectory()) {
			return walk.isEntered(entry.name) ? filesUnder(full, walk) : [];
		}

		return entry.isFile() && walk.isWanted(full) ? [full] : [];
	});
}

function isScript(file: string): boolean {
	return SCRIPT.test(file) && !DECLARATIONS.test(file);
}

function isText(file: string): boolean {
	return TEXT_FILE.test(file) && !SKIPPED_TEXT.has(path.basename(file));
}

function isInDotFolder(relative: string): boolean {
	return path
		.dirname(relative)
		.split(path.sep)
		.some((folder) => folder.startsWith(".") && folder !== ".");
}
